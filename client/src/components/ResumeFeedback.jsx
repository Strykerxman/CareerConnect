import React from 'react';
const CATEGORIES = [
  { key: 'content', label: 'Content' },
  { key: 'skills', label: 'Skills' },
  { key: 'formatting', label: 'Formatting' },
];

// US-15 / Task 15.3 — Shows AI feedback for one resume.
function ResumeFeedback({ state, onClose }) {
  if (state.loading) {
    return (
      <section className="resume-feedback" aria-live="polite">
        <p role="status">Analyzing your resume. This can take up to a minute...</p>
      </section>
    );
  }

  if (state.error) {
    return (
      <section className="resume-feedback" aria-live="polite">
        <div className="banner error" role="alert">{state.error}</div>
        <p className="resume-feedback-note">Your resume was not changed.</p>
        <button type="button" className="button secondary" onClick={onClose}>Close</button>
      </section>
    );
  }

  const { summary, strengths, suggestions } = state.feedback;

  return (
    <section className="resume-feedback" aria-live="polite" aria-label="AI resume feedback">
      <div className="resume-feedback-header">
        <h3>AI Feedback</h3>
        <button type="button" className="button secondary" onClick={onClose}>Close</button>
      </div>

      <p>{summary}</p>

      {strengths.length > 0 && (
        <>
          <h4>Strengths</h4>
          <ul>
            {strengths.map(strength => <li key={strength}>{strength}</li>)}
          </ul>
        </>
      )}

      {CATEGORIES.map(({ key, label }) => {
        const items = suggestions.filter(item => item.category === key);
        if (items.length === 0) return null;
        return (
          <div key={key}>
            <h4>{label}</h4>
            <ul>
              {items.map(item => (
                <li key={item.title}>
                  <strong>{item.title.replace(/[.:]\s*$/, '')}:</strong> {item.detail}
                </li>
              ))}
            </ul>
          </div>
        );
      })}

      <p className="resume-feedback-note">
        Generated by Google Gemini from your resume text, with contact details removed.
        AI suggestions can be wrong. Use your own judgment before changing your resume.
      </p>
    </section>
  );
}

export default ResumeFeedback;
